/** 池 -> 最近用过的句子（池内去重窗口，抄 news.js 的 recentByPool 思路） */
const recentByPool = new Map();
const RECENT_WINDOW = 12;
/** 池健康度（§3.7.3）：hits 命中次数 / repeatHits 命中去重窗口的次数 */
const health = new Map();

function poolOf(kind, scene) {
  const p = POOLS[kind];
  if (!p) return null;
  return p[scene] || p.idle || null;
}

function bumpHealth(key, repeat) {
  let h = health.get(key);
  if (!h) {
    h = { hits: 0, repeatHits: 0 };
    health.set(key, h);
  }
  h.hits += 1;
  if (repeat) h.repeatHits += 1;
}

/** 取池健康度快照（日志 / 测试用）：repeatHits/hits 高的池就是该补文案的池 */
function healthSnapshot() {
  const out = {};
  for (const [k, v] of health) {
    out[k] = { hits: v.hits, repeatHits: v.repeatHits, repeatRate: v.hits ? v.repeatHits / v.hits : 0 };
  }
  return out;
}

function resetHealth() {
  health.clear();
  recentByPool.clear();
}

/**
 * 变量替换：{pct} 是**绝对值**百分数（23 表示亏 23%），由调用方保证数字真实。
 * 变量缺失时返回 null 而不是留下 `{pct}`——宁可换一条文案，也不能把模板占位符发到屏幕上。
 */
function fill(template, vars) {
  let bad = false;
  const out = template.replace(/\{(\w+)\}/g, (m, k) => {
    const v = vars ? vars[k] : null;
    if (v == null || v === '') {
      bad = true;
      return m;
    }
    return String(v);
  });
  return bad ? null : out;
}

/**
 * 选一条文案。
 * @param {string} kind  说话人类型：small/mid/big/hot/inst/mm，或 'playerB'
 * @param {string} scene 情境：deepLoss/win/liquidation/idle，或 playerB 的三个情境
 * @param {object} [vars] 变量槽（只允许纯数字/档位，禁止传入账户名）
 * @returns {string|null} 取不到池时返回 null（调用方应静默丢弃，不要退回随机句）
 */
function pickText(kind, scene, vars) {
  const pool = poolOf(kind, scene);
  if (!pool || !pool.length) return null;
  const key = `${kind}.${scene}`;
  let recent = recentByPool.get(key);
  if (!recent) {
    recent = [];
    recentByPool.set(key, recent);
  }
  // 随机起点扫一圈，取第一条「不在去重窗口里且变量能填满」的候选；
  // 全都在窗口里就用起点那条（并记一次重复，供池健康度统计）
  const start = Math.floor(Math.random() * pool.length);
  let chosen = null;
  let body = null;
  let repeated = false;
  for (let i = 0; i < pool.length; i++) {
    const s = pool[(start + i) % pool.length];
    if (recent.includes(s)) continue;
    const filled = fill(s, vars);
    if (filled == null) continue;
    chosen = s;
    body = filled;
    break;
  }
  if (chosen == null) {
    const s = pool[start];
    body = fill(s, vars);
    if (body == null) return null;
    chosen = s;
    repeated = true;
  }
  recent.push(chosen);
  if (recent.length > RECENT_WINDOW) recent.shift();
  bumpHealth(key, repeated);

  const prefixAllowed = !NO_PREFIX.has(kind) && (config.danmaku && config.danmaku.prefix !== false);
  const prefix = prefixAllowed ? PREFIX[Math.floor(Math.random() * PREFIX.length)] : '';
  // 前缀 + 主句：句子里已有省略号或已带语气词时不再加前缀，避免「……唉，」这种叠字
  const skip = /^(唉|真行|不是|我服了|……)/.test(body) || body.endsWith('。');

  return skip ? body : prefix + body;
}

module.exports = { POOLS, PREFIX, pickText, healthSnapshot, resetHealth };
